#!/usr/bin/env node
/**
 * Generates src/components/codicon-map.ts (name -> glyph character) from
 * @vscode/codicons' own dist/codicon.csv (short_name,character,unicode),
 * the same short names the desktop's CSS classes use (`codicon-<name>`) —
 * so `<Codicon name="file" />` on mobile names the identical glyph the
 * desktop's `<Codicon name="file" />` (apps/desktop/src/components/ui/
 * codicon.tsx) would show.
 *
 * Not vendored under src/upstream/ (this isn't hermes-agent code) and not
 * tied to the UPSTREAM.json commit (this is @vscode/codicons' own package,
 * pinned by package.json/package-lock.json like any other npm dependency)
 * — a one-off/occasional generator, re-run by hand after bumping
 * @vscode/codicons.
 *
 * Usage: node scripts/generate-codicon-map.mjs
 */

import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = path.resolve(__dirname, '..')
const CSV_PATH = path.join(REPO_ROOT, 'node_modules', '@vscode', 'codicons', 'dist', 'codicon.csv')
const DEST = path.join(REPO_ROOT, 'src', 'components', 'codicon-map.ts')

function fail(message) {
  console.error(`generate-codicon-map: ${message}`)
  process.exit(1)
}

let csv
try {
  csv = readFileSync(CSV_PATH, 'utf8')
} catch {
  fail(`could not read ${CSV_PATH} — is @vscode/codicons installed?`)
}

const lines = csv.trim().split('\n')
const header = lines.shift()

if (header !== 'short_name,character,unicode') {
  fail(`unexpected codicon.csv header, update this script: "${header}"`)
}

const entries = []

for (const line of lines) {
  const [shortName, , unicode] = line.split(',')

  if (!shortName || !unicode) {
    fail(`malformed codicon.csv row: "${line}"`)
  }

  entries.push([shortName, unicode.trim()])
}

if (entries.length === 0) {
  fail('parsed zero icons from codicon.csv')
}

const body = entries.map(([name, hex]) => `  '${name}': '\\u{${hex.toLowerCase()}}'`).join(',\n')

const content = `// GENERATED by scripts/generate-codicon-map.mjs from
// node_modules/@vscode/codicons/dist/codicon.csv — do not hand-edit; re-run
// the script instead. Short names match the desktop's CSS classes
// (codicon-<name>) exactly, so an icon name ports 1:1 between surfaces.

export const CODICON_GLYPHS: Record<string, string> = {
${body}
}

export type CodiconName = keyof typeof CODICON_GLYPHS
`

writeFileSync(DEST, content)

const eslintBin = path.join(REPO_ROOT, 'node_modules', 'eslint', 'bin', 'eslint.js')
const prettierBin = path.join(REPO_ROOT, 'node_modules', 'prettier', 'bin', 'prettier.cjs')

execFileSync(process.execPath, [eslintBin, '--fix', DEST], { cwd: REPO_ROOT, stdio: 'inherit' })
execFileSync(process.execPath, [prettierBin, '--write', DEST], { cwd: REPO_ROOT, stdio: 'inherit' })

console.log(`generate-codicon-map: wrote ${path.relative(REPO_ROOT, DEST)} (${entries.length} icons)`)
